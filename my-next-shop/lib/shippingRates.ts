/** 무게(kg)에 맞는 요금. 표의 다음 구간으로 올림하며, 표의 마지막 무게를 넘으면 null (별도 문의) */
export function lookupShippingFee(weight: number, rates: RatePair[]): number | null {
  if (!(weight > 0)) return 0;
  const sorted = [...rates].sort((a, b) => a[0] - b[0]);
  const row = sorted.find(([w]) => weight <= w + 1e-9);
  return row ? row[1] : null;
}
